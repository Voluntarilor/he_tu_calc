def test_pressure_gost34347(p_des_mpa, t_des_c, mat_code):
    _, _, s_ratio = MATERIALS.get(mat_code, ("Сталь", 45.0, 1.0))
    t_factor = 1.0 if t_des_c <= 50 else min(1.25, s_ratio + max(0.0, (t_des_c - 100.0) * 0.0007))
